package com.darkrifts.client;

import com.darkrifts.DarkRifts;
import com.darkrifts.entity.MirrorSovereign;
import com.darkrifts.entity.RiftReaver;
import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.client.renderer.culling.Frustum;
import net.minecraft.client.renderer.entity.EntityRendererProvider;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.Mth;
import org.joml.Matrix4f;
import software.bernie.geckolib.model.DefaultedEntityGeoModel;
import software.bernie.geckolib.renderer.GeoEntityRenderer;
import software.bernie.geckolib.renderer.layer.AutoGlowingGeoLayer;

/**
 * The Mirror Sovereign: its own levitating model (geo/animations/texture mirror_sovereign, generated by
 * tools/sovereign_model.py), scaled 1.6x. While it climbs out of the sky it draws a rift twice the size of
 * the Reaver's and a pillar of red light falling from it onto the dais.
 */
public class MirrorSovereignRenderer extends GeoEntityRenderer<MirrorSovereign> {
    public MirrorSovereignRenderer(EntityRendererProvider.Context context) {
        super(context, new DefaultedEntityGeoModel<MirrorSovereign>(ResourceLocation.fromNamespaceAndPath(DarkRifts.MODID, "mirror_sovereign")));
        addRenderLayer(new AutoGlowingGeoLayer<>(this));
        withScale(MirrorSovereign.MODEL_SCALE);
        this.shadowRadius = 3.4F;
    }

    @Override
    public void render(MirrorSovereign entity, float entityYaw, float partialTick, PoseStack poseStack,
                       MultiBufferSource bufferSource, int packedLight) {
        super.render(entity, entityYaw, partialTick, poseStack, bufferSource, packedLight);
        if (!entity.isRiftActive()) {
            return;
        }
        float age = entity.getRiftAge(partialTick);
        float open = RiftReaver.riftOpen(age);
        if (open <= 0.0F) {
            return;
        }
        double y = Mth.lerp(partialTick, entity.yOld, entity.getY());
        float time = entity.level().getGameTime() + partialTick;
        poseStack.pushPose();
        poseStack.translate(0.0, entity.getRiftY() - y, 0.0);
        poseStack.pushPose();
        poseStack.scale(2.0F, 1.0F, 2.0F);
        SkyRiftRenderer.draw(poseStack, bufferSource, open, time);
        poseStack.popPose();
        // a pillar of red light from the tear to the dais
        Matrix4f m = poseStack.last().pose();
        VertexConsumer glow = bufferSource.getBuffer(RenderType.lightning());
        float flick = 0.85F + 0.15F * (float) Math.sin(time * 1.1F);
        float drop = (float) (entity.getRiftY() - entity.getY() + MirrorSovereign.HOVER);
        FxDraw.beam(glow, m, 0.0F, -0.5F, 0.0F, -drop - 2.0F, 2.4F * open * flick, 255, 60, 90, (int) (110 * open));
        FxDraw.beam(glow, m, 0.0F, -0.5F, 0.0F, -drop - 2.0F, 0.9F * open, 255, 220, 230, (int) (170 * open));
        poseStack.popPose();
    }

    @Override
    public boolean shouldRender(MirrorSovereign entity, Frustum frustum, double camX, double camY, double camZ) {
        return entity.isRiftActive() || super.shouldRender(entity, frustum, camX, camY, camZ);
    }
}
